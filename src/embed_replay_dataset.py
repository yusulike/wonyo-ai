"""
One-time generator: embeds the 2021 Q2 replay candle window into src/replay_data.py.

Rationale: Vercel's Python runtime bundles git-tracked files inside src/ (proven by
wonyo_nn_model.onnx reaching the lambda), but files under data/ never made it into
the bundle regardless of includeFiles / .vercelignore negation. Embedding the
replay window as an imported Python module guarantees availability server-side.
"""

import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pandas as pd

PARQUET_PATH = Path("data/candles/bitmex_2021_q2_15m.parquet")
OUT_PATH = Path(__file__).resolve().parent / "replay_data.py"

# Same window web_api.load_replay_candles slices for replay mode (starts May 2021 crash)
WINDOW_START = 4500
WINDOW_SIZE = 600  # generous headroom over the max API limit (~150)

def main():
    df = pd.read_parquet(PARQUET_PATH)
    window = df.iloc[WINDOW_START:WINDOW_START + WINDOW_SIZE]

    lines = [
        '"""',
        'Wonyo-AI Replay Dataset (auto-generated by src/embed_replay_dataset.py)',
        f'BitMEX XBTUSD 15m candles, rows {WINDOW_START}..{WINDOW_START + WINDOW_SIZE} of the 2021 Q2',
        'dataset - the May 19-21 crash & rebound window. Imported (not file-loaded) so the',
        'Vercel serverless bundle always carries it via Python import tracing.',
        '"""',
        "",
        "REPLAY_CANDLES = [",
    ]
    for r in window.itertuples(index=False):
        ts = pd.Timestamp(r.timestamp).isoformat()
        lines.append(
            f"    {{\"timestamp\": \"{ts}\", \"open\": {r.open:.1f}, \"high\": {r.high:.1f}, "
            f"\"low\": {r.low:.1f}, \"close\": {r.close:.1f}, \"volume\": {float(r.volume):.1f}}},"
        )
    lines.append("]")
    lines.append("")

    OUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Embedded {len(window)} candles ({window['timestamp'].min()} .. {window['timestamp'].max()}) -> {OUT_PATH}")

if __name__ == "__main__":
    main()
